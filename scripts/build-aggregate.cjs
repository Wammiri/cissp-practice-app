/*
 * Aggregation phase
 *  - Merges the 8 per-domain question files into:
 *      questions/cissp-question-bank.json
 *      questions/cissp-question-bank.md
 *  - Generates 10 weighted 100-question practice tests that PARTITION the bank
 *    (each question used exactly once across the 10 tests):
 *      tests/test-01.json .. tests/test-10.json
 *      tests/test-manifest.json
 *
 * The bank's per-domain counts are exactly 10x the CISSP exam weights, so each
 * test receives 16/10/13/13/13/12/13/10 questions per domain (= 100) with no
 * repeats across tests. Tests reference questions by ID (the bank is the single
 * source of truth).
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const Q = path.join(ROOT, 'questions');
const TESTS = path.join(ROOT, 'tests');
const NUM_TESTS = 10;

const DOMAIN_FILES = [
  { n: 1, name: 'Security and Risk Management',          file: 'domain-01-security-risk-management.json',          weight: 16 },
  { n: 2, name: 'Asset Security',                        file: 'domain-02-asset-security.json',                    weight: 10 },
  { n: 3, name: 'Security Architecture and Engineering', file: 'domain-03-security-architecture-engineering.json', weight: 13 },
  { n: 4, name: 'Communication and Network Security',    file: 'domain-04-communication-network-security.json',    weight: 13 },
  { n: 5, name: 'Identity and Access Management (IAM)',  file: 'domain-05-identity-access-management.json',         weight: 13 },
  { n: 6, name: 'Security Assessment and Testing',       file: 'domain-06-security-assessment-testing.json',       weight: 12 },
  { n: 7, name: 'Security Operations',                   file: 'domain-07-security-operations.json',               weight: 13 },
  { n: 8, name: 'Software Development Security',         file: 'domain-08-software-development-security.json',      weight: 10 },
];

// deterministic PRNG so test composition is reproducible
function rng(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffle(arr, seed) {
  const rand = rng(seed);
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// ---- load domains ----
const domains = DOMAIN_FILES.map(d => {
  const data = JSON.parse(fs.readFileSync(path.join(Q, d.file), 'utf8'));
  return { ...d, questions: data.questions };
});

const allQuestions = [].concat(...domains.map(d => d.questions));

// ---- difficulty / type tallies ----
function tally(qs) {
  const diff = { easy: 0, medium: 0, hard: 0 };
  const type = {};
  for (const q of qs) {
    diff[q.difficulty] = (diff[q.difficulty] || 0) + 1;
    type[q.question_type] = (type[q.question_type] || 0) + 1;
  }
  return { diff, type };
}
const bankTally = tally(allQuestions);

// ---- build merged bank ----
const bank = {
  meta: {
    title: 'CISSP Practice Question Bank',
    generated_by: 'scripts/build-aggregate.cjs',
    sources: DOMAIN_FILES.map(d => `questions/${d.file}`),
    schema: '04_schemas/question_schema.md',
    total_questions: allQuestions.length,
    domains: domains.map(d => ({ domain_number: d.n, domain: d.name, weight_percent: d.weight, question_count: d.questions.length })),
    difficulty_distribution: bankTally.diff,
    question_type_distribution: bankTally.type,
    id_format: 'CISSP-D0<domain>-Q####',
  },
  questions: allQuestions,
};
fs.writeFileSync(path.join(Q, 'cissp-question-bank.json'), JSON.stringify(bank, null, 2) + '\n', 'utf8');

// ---- build markdown bank ----
function ansText(q) {
  const a = q.correct_answer;
  if (Array.isArray(a)) return a.join(', ');
  return String(a);
}
const md = [];
md.push('# CISSP Practice Question Bank');
md.push('');
md.push(`> ${allQuestions.length} original CISSP-style questions across 8 domains. Generated by \`scripts/build-aggregate.cjs\`.`);
md.push('');
md.push('| # | Domain | Weight | Questions |');
md.push('|---|--------|--------|-----------|');
for (const d of domains) md.push(`| ${d.n} | ${d.name} | ${d.weight}% | ${d.questions.length} |`);
md.push(`| | **Total** | **100%** | **${allQuestions.length}** |`);
md.push('');
for (const d of domains) {
  md.push('');
  md.push(`## Domain ${d.n}: ${d.name}`);
  md.push('');
  for (const q of d.questions) {
    md.push(`### ${q.id} — ${q.topic} / ${q.subtopic}  _(${q.difficulty}, ${q.question_type})_`);
    md.push('');
    md.push(q.question);
    md.push('');
    if (q.prompts) {
      q.prompts.forEach((p, i) => md.push(`${i + 1}. ${p}`));
      md.push('');
    }
    for (const o of q.options) md.push(`- **${o.label}.** ${o.text}`);
    md.push('');
    md.push(`**Correct answer:** ${ansText(q)}`);
    md.push('');
    md.push(`**Why correct:** ${q.explanation.why_correct}`);
    const ww = q.explanation.why_others_are_wrong || {};
    if (Object.keys(ww).length) {
      md.push('');
      md.push('**Why the others are wrong:**');
      for (const k of Object.keys(ww)) md.push(`- ${k}: ${ww[k]}`);
    }
    md.push('');
    md.push(`*Source: ${q.source_reference.syllabus_section}*`);
    md.push('');
    md.push('---');
    md.push('');
  }
}
fs.writeFileSync(path.join(Q, 'cissp-question-bank.md'), md.join('\n') + '\n', 'utf8');

// ---- build 10 weighted tests that partition the bank ----
// For each domain, shuffle its question IDs, then split into NUM_TESTS equal
// chunks (count is exactly divisible by 10 for every domain).
fs.mkdirSync(TESTS, { recursive: true });

const perTestDomainChunks = domains.map(d => {
  const ids = shuffle(d.questions.map(q => q.id), 1000 + d.n);
  const per = ids.length / NUM_TESTS; // integer by construction
  const chunks = [];
  for (let t = 0; t < NUM_TESTS; t++) chunks.push(ids.slice(t * per, (t + 1) * per));
  return { d, chunks };
});

const manifestTests = [];
const usedIds = new Set();
for (let t = 0; t < NUM_TESTS; t++) {
  const idNum = String(t + 1).padStart(2, '0');
  const testId = `test-${idNum}`;
  const domainDistribution = {};
  let questionIds = [];
  for (const { d, chunks } of perTestDomainChunks) {
    domainDistribution[d.name] = chunks[t].length;
    questionIds = questionIds.concat(chunks[t]);
  }
  // interleave by domain order already; shuffle the whole test order deterministically
  questionIds = shuffle(questionIds, 7000 + t);
  questionIds.forEach(id => usedIds.add(id));
  const test = {
    test_id: testId,
    title: `CISSP Practice Test ${idNum}`,
    total_questions: questionIds.length,
    domain_distribution: domainDistribution,
    questions: questionIds,
  };
  fs.writeFileSync(path.join(TESTS, `${testId}.json`), JSON.stringify(test, null, 2) + '\n', 'utf8');
  manifestTests.push({
    test_id: testId,
    title: test.title,
    total_questions: test.total_questions,
    domain_distribution: domainDistribution,
    file: `tests/${testId}.json`,
  });
}

const manifest = {
  meta: {
    title: 'CISSP Practice Test Manifest',
    generated_by: 'scripts/build-aggregate.cjs',
    question_bank: 'questions/cissp-question-bank.json',
    total_tests: NUM_TESTS,
    questions_per_test: 100,
    weighting: 'Each test mirrors the CISSP exam domain weights; the 10 tests partition the full bank with no question repeated.',
    domain_weights: Object.fromEntries(domains.map(d => [d.name, d.weight])),
  },
  tests: manifestTests,
};
fs.writeFileSync(path.join(TESTS, 'test-manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');

// ---- console summary ----
console.log('Bank:', allQuestions.length, 'questions ->', 'questions/cissp-question-bank.json + .md');
console.log('Difficulty:', JSON.stringify(bankTally.diff), '| Types:', JSON.stringify(bankTally.type));
console.log('Tests:', NUM_TESTS, 'x 100 =', NUM_TESTS * 100, '| unique IDs used:', usedIds.size);
manifestTests.forEach(t => {
  const dd = Object.values(t.domain_distribution).reduce((s, n) => s + n, 0);
  console.log(`  ${t.test_id}: ${dd} questions, dist ${JSON.stringify(t.domain_distribution).slice(0, 60)}...`);
});
